"""4. downscaling:"""

def max_downscale(img_array, down_factor):
    h, w, c = img_array.shape
    new_h = h // down_factor
    new_w = w // down_factor

    max_downscaled = np.zeros((new_h, new_w, c), dtype=np.float32)

    for i in range(new_h):
        for j in range(new_w):
            # Define block boundaries
            h_start, h_end = i * down_factor, (i + 1) * down_factor
            w_start, w_end = j * down_factor, (j + 1) * down_factor

            # Extract the block
            block = img_array[h_start:h_end, w_start:w_end, :]

            # Calculate max for each channel
            for channel in range(c):
                max_downscaled[i, j, channel] = np.max(block[:, :, channel])

    return max_downscaled

