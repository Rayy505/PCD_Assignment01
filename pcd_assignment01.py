def save_and_download(img_array, filename):
    rescaled = np.clip(img_array, 0, 255).astype(np.uint8)
    img = Image.fromarray(rescaled)
    img.save(filename)
    files.download(filename)

def compare_methods(img_path, down_factor, up_factor, re_up_factor):
    img_array = get_img_array(img_path)

    # Downscaling results
    max_dn = max_downscale(img_array, down_factor)
    mean_dn = mean_downscale(img_array, down_factor)
    min_dn = min_downscale(img_array, down_factor)

    # Upscaling results (from Original)
    nn_up = nn_upscale(img_array, up_factor)
    bl_up = bilinear_upscale(img_array, up_factor)
    bc_up = bicubic_upscale(img_array, up_factor)

    # Upscaling from Mean Downscaled image (Reconstruction/Rescaling)
    nn_recon = nn_upscale(mean_dn, re_up_factor)
    bl_recon = bilinear_upscale(mean_dn, re_up_factor)
    bc_recon = bicubic_upscale(mean_dn, re_up_factor)

    # Visualization
    fig, axes = plt.subplots(3, 4, figsize=(20, 15))

    row1 = [("Original", img_array), ("Max Downscaling", max_dn), ("Average Downscaling", mean_dn), ("Min Downscaling", min_dn)]
    for i, (title, data) in enumerate(row1):
        axes[0, i].imshow(np.clip(data, 0, 255).astype(np.uint8))
        axes[0, i].set_title(f"{title}\n{data.shape[1]}x{data.shape[0]}")
        axes[0, i].axis('off')

    row2 = [("Original", img_array), ("Nearest Neighbor Upscaling", nn_up), ("Bilinear Upscaling", bl_up), ("Bicubic Upscaling", bc_up)]
    for i, (title, data) in enumerate(row2):
        axes[1, i].imshow(np.clip(data, 0, 255).astype(np.uint8))
        axes[1, i].set_title(f"{title}\n{data.shape[1]}x{data.shape[0]}")
        axes[1, i].axis('off')

    row3 = [("Mean Downscaling", mean_dn), ("Nearest Neighbor Rescaling", nn_recon), ("Bilinear Rescaling", bl_recon), ("Bicubic Rescaling", bc_recon)]
    for i, (title, data) in enumerate(row3):
        axes[2, i].imshow(np.clip(data, 0, 255).astype(np.uint8))
        axes[2, i].set_title(f"{title}\n{data.shape[1]}x{data.shape[0]}")
        axes[2, i].axis('off')

    plt.tight_layout()
    plt.show()

    # Downloads
    print("Starting downloads...")
    save_and_download(max_dn, "max_downscaled.jpg")
    save_and_download(mean_dn, "mean_downscaled.jpg")
    save_and_download(min_dn, "min_downscaled.jpg")
    save_and_download(nn_up, "nn_upscaled.jpg")
    save_and_download(bl_up, "bilinear_upscaled.jpg")
    save_and_download(bc_up, "bicubic_upscaled.jpg")
    save_and_download(nn_recon, "nn_reconstructed.jpg")
    save_and_download(bl_recon, "bilinear_reconstructed.jpg")
    save_and_download(bc_recon, "bicubic_reconstructed.jpg")

