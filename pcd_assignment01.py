def nn_upscale(img_array, up_factor):
    h, w, c = img_array.shape
    new_h = h * up_factor
    new_w = w * up_factor

    nn_upscaled = np.zeros((new_h, new_w, c), dtype=np.float32)

  # Find the nearest neighbor's pixel value
    for i in range(new_h):
        for j in range(new_w):
            orig_i = i // up_factor
            orig_j = j // up_factor

            # Assign the pixel value from the original image
            nn_upscaled[i, j, :] = img_array[orig_i, orig_j, :]

    return nn_upscaled

def bilinear_upscale(img_array, up_factor):
    h, w, c = img_array.shape
    new_h = h * up_factor
    new_w = w * up_factor

    bilinear_upscaled = np.zeros((new_h, new_w, c), dtype=np.float32)

    for i in range(new_h):
        for j in range(new_w):
            # Map output coordinates to input coordinates (floating point)
            orig_i = i / up_factor
            orig_j = j / up_factor

            # Find the coordinates of the 4 surrounding pixels
            i_low = int(np.floor(orig_i))
            i_high = min(i_low + 1, h - 1)
            j_low = int(np.floor(orig_j))
            j_high = min(j_low + 1, w - 1)

            # Calculate the fractional weights
            di = orig_i - i_low
            dj = orig_j - j_low

            # Perform bilinear interpolation for each channel
            for channel in range(c):
                # Get values of the 4 neighbors
                v1 = img_array[i_low, j_low, channel]
                v2 = img_array[i_high, j_low, channel]
                v3 = img_array[i_low, j_high, channel]
                v4 = img_array[i_high, j_high, channel]

                # Linear interpolation along i then j
                val = (v1 * (1 - di) * (1 - dj) +
                       v2 * di * (1 - dj) +
                       v3 * (1 - di) * dj +
                       v4 * di * dj)

                bilinear_upscaled[i, j, channel] = val

    return bilinear_upscaled

def bicubic_upscale(img_array, up_factor):
    h, w, c = img_array.shape
    new_h = h * up_factor
    new_w = w * up_factor
    def get_weights(x):
        a = -0.5
        x = np.abs(x)
        w = np.zeros_like(x)
        mask1 = x <= 1
        mask2 = (x > 1) & (x < 2)
        w[mask1] = (a + 2) * (x[mask1]**3) - (a + 3) * (x[mask1]**2) + 1
        w[mask2] = a * (x[mask2]**3) - 5 * a * (x[mask2]**2) + 8 * a * x[mask2] - 4 * a
        return w

    x_out = np.arange(new_w) / up_factor
    y_out = np.arange(new_h) / up_factor

    # Indices of the 4x4 neighborhood
    x_low = np.floor(x_out).astype(int)
    y_low = np.floor(y_out).astype(int)

    # Precompute weights
    wx = np.stack([get_weights(x_out - (x_low + i)) for i in range(-1, 3)], axis=0)
    wy = np.stack([get_weights(y_out - (y_low + i)) for i in range(-1, 3)], axis=0)

    # Output array
    bicubic_upscaled = np.zeros((new_h, new_w, c), dtype=np.float32)

    for channel in range(c):
        for m in range(4):
            for n in range(4):
                # Neighbor coordinates
                curr_y = np.clip(y_low + m - 1, 0, h - 1)
                curr_x = np.clip(x_low + n - 1, 0, w - 1)

                # Sample from original image
                samples = img_array[curr_y[:, None], curr_x, channel]

                # Apply weights
                bicubic_upscaled[:, :, channel] += samples * wy[m][:, None] * wx[n]

    bicubc_upscaled = np.clip(bicubic_upscaled, 0, 255)
    return bicubc_upscaled

